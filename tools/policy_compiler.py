#!/usr/bin/env python3
import hashlib
import json
import sys


def compile_policy(json_path, cpp_out, lean_out):
    with open(json_path, "r", encoding="ascii") as f:
        data = json.load(f)

    labels = data["labels"]
    if not (1 <= len(labels) <= 64):
        raise ValueError("labels must have between 1 and 64 entries")
    if len(set(labels)) != len(labels):
        raise ValueError("duplicate label names")

    label_bit = {name: (1 << idx) for idx, name in enumerate(labels)}

    def mask_of(names):
        m = 0
        for n in names:
            if n not in label_bit:
                raise ValueError(f"unknown label: {n}")
            m |= label_bit[n]
        return m

    canonical_json = json.dumps(data, sort_keys=True, separators=(",", ":")).encode("ascii")
    policy_sha256 = hashlib.sha256(canonical_json).hexdigest()

    tools = sorted(data["tools"].items())
    rules = []
    for name, cfg in tools:
        rules.append((name, mask_of(cfg["taint"]), mask_of(cfg["clearance"])))

    cpp_lines = [
        "#pragma once",
        "// AUTO-GENERATED by tools/policy_compiler.py -- DO NOT EDIT",
        "#include <array>",
        "#include <cstdint>",
        "#include <string_view>",
        "",
        "namespace mcp_lattice::policy {",
        "",
        f'inline constexpr std::string_view POLICY_NAME = "{data["policy_name"]}";',
        f'inline constexpr std::string_view POLICY_SHA256 = "{policy_sha256}";',
        "",
        "struct ToolRule {",
        "    std::string_view name;",
        "    std::uint64_t taint_mask;",
        "    std::uint64_t clearance_mask;",
        "};",
        "",
    ]
    for idx, name in enumerate(labels):
        cpp_lines.append(f"inline constexpr std::uint64_t LABEL_{name} = 1ULL << {idx};")
    cpp_lines.append("")
    cpp_lines.append(f"inline constexpr std::array<ToolRule, {len(rules)}> RULES = {{{{")
    for name, t_mask, c_mask in rules:
        cpp_lines.append(f'    {{"{name}", 0x{t_mask:016x}ULL, 0x{c_mask:016x}ULL}},')
    cpp_lines.append("}};")
    cpp_lines.append("")
    cpp_lines.append("} // namespace mcp_lattice::policy")
    cpp_lines.append("")

    with open(cpp_out, "w", encoding="ascii") as f:
        f.write("\n".join(cpp_lines))

    lean_lines = [
        "-- AUTO-GENERATED by tools/policy_compiler.py -- DO NOT EDIT",
        f"-- Policy: {data['policy_name']} (SHA-256: {policy_sha256})",
        "",
        "namespace GeneratedPolicy",
        "",
    ]
    for idx, name in enumerate(labels):
        lean_lines.append(f"def LABEL_{name} : Fin 64 := Fin.mk {idx} (by decide)")
    lean_lines.append("")
    for name, t_mask, c_mask in rules:
        lean_lines.append(
            f"def rule_{name} : Rule := "
            f"{{ taint := BitVec.ofNat 64 {t_mask}, clearance := BitVec.ofNat 64 {c_mask} }}"
        )
    lean_lines.append("")
    lean_lines.append("end GeneratedPolicy")
    lean_lines.append("")

    with open(lean_out, "w", encoding="ascii") as f:
        f.write("\n".join(lean_lines))

    print(f"Compiled {len(rules)} rules ({len(labels)} labels) | SHA-256: {policy_sha256}")


if __name__ == "__main__":
    compile_policy(sys.argv[1], sys.argv[2], sys.argv[3])
